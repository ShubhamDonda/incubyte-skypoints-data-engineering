    MEMBER_TYPE = s.MEMBER_TYPE,
    AGE = s.AGE,
    STALE_MEMBER = COALESCE(s.STALE_MEMBER, FALSE),
    SOURCE_UPDATED_AT = s.SOURCE_UPDATED_AT,
    INGESTED_AT = s.INGESTED_AT,
    SOURCE_FILE = s.SOURCE_FILE,
    RECORD_HASH = s.RECORD_HASH,
    LAST_BATCH_ID = s.BATCH_ID,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    GLOBAL_MEMBER_ID, SOURCE_COUNTRY, SOURCE_MEMBER_ID, MEMBER_NAME, DOB,
    ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE_CODE,
    POSTAL_CODE, IS_ACTIVE, MEMBER_TYPE, AGE, STALE_MEMBER, SOURCE_UPDATED_AT,
    INGESTED_AT, SOURCE_FILE, RECORD_HASH, LAST_BATCH_ID
) VALUES (
    s.GLOBAL_MEMBER_ID, s.SOURCE_COUNTRY, s.SOURCE_MEMBER_ID, s.MEMBER_NAME,
    s.DOB, s.ENROLLMENT_DATE, s.LAST_FLIGHT_DATE, s.TIER_CODE, s.AGENT_NAME,
    s.STATE_CODE, s.POSTAL_CODE, s.IS_ACTIVE, s.MEMBER_TYPE, s.AGE,
    COALESCE(s.STALE_MEMBER, FALSE), s.SOURCE_UPDATED_AT, s.INGESTED_AT,
    s.SOURCE_FILE, s.RECORD_HASH, s.BATCH_ID
);

