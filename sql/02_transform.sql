-- 5) Flatten partner JSON. Contract: JSON member_id is the GLOBAL_MEMBER_ID.
-- Do not join on a country-local source ID unless it resolves uniquely through
-- MEMBER_IDENTITY_MAP; ambiguous/unmatched transactions are retained for DQ.
MERGE INTO SKYPOINTS_CURATED.REDEMPTION_FLAT t
USING (
    SELECT
        f.VALUE:txn_id::STRING AS TXN_ID,
        m.GLOBAL_MEMBER_ID AS GLOBAL_MEMBER_ID,
        f0.RAW_PAYLOAD:member_id::STRING AS FEED_MEMBER_ID,
        TRY_TO_DATE(f0.RAW_PAYLOAD:feed_date::STRING, 'YYYYMMDD') AS FEED_DATE,
        TRY_TO_DATE(f.VALUE:txn_date::STRING, 'YYYYMMDD') AS TXN_DATE,
        f.VALUE:partner::STRING AS PARTNER,
        TRY_TO_NUMBER(f.VALUE:miles_redeemed::STRING) AS MILES_REDEEMED,
        UPPER(f.VALUE:status::STRING) AS STATUS,
        IFF(m.GLOBAL_MEMBER_ID IS NULL, 'UNMATCHED_MEMBER_ID', 'MATCHED') AS MEMBER_JOIN_STATUS,
        f0.SOURCE_FILE AS SOURCE_FILE,
        f0.INGESTED_AT AS INGESTED_AT
    FROM SKYPOINTS_RAW.RAW_REDEMPTION_LANDING f0,
         LATERAL FLATTEN(INPUT => f0.RAW_PAYLOAD:redemptions) f
    LEFT JOIN SKYPOINTS_CURATED.MEMBER_CURRENT m
      ON m.GLOBAL_MEMBER_ID = f0.RAW_PAYLOAD:member_id::STRING
    WHERE f0.INGESTED_AT >= :BATCH_START AND f0.INGESTED_AT < :BATCH_END
      AND NULLIF(f.VALUE:txn_id::STRING, '') IS NOT NULL
      AND TRY_TO_DATE(f0.RAW_PAYLOAD:feed_date::STRING, 'YYYYMMDD') IS NOT NULL
      AND TRY_TO_DATE(f.VALUE:txn_date::STRING, 'YYYYMMDD') IS NOT NULL
      AND TRY_TO_NUMBER(f.VALUE:miles_redeemed::STRING) >= 0
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY f.VALUE:txn_id::STRING
        ORDER BY f0.INGESTED_AT DESC, f0.SOURCE_FILE DESC
    ) = 1
) s
ON t.TXN_ID = s.TXN_ID
WHEN MATCHED AND s.INGESTED_AT > t.INGESTED_AT THEN UPDATE SET
    GLOBAL_MEMBER_ID=s.GLOBAL_MEMBER_ID,
    FEED_MEMBER_ID=s.FEED_MEMBER_ID,
    FEED_DATE=s.FEED_DATE,
    TXN_DATE=s.TXN_DATE,
    PARTNER=s.PARTNER,
    MILES_REDEEMED=s.MILES_REDEEMED,
    STATUS=s.STATUS,
    MEMBER_JOIN_STATUS=s.MEMBER_JOIN_STATUS,
    SOURCE_FILE=s.SOURCE_FILE,
    INGESTED_AT=s.INGESTED_AT
WHEN NOT MATCHED THEN INSERT (
    TXN_ID, GLOBAL_MEMBER_ID, FEED_MEMBER_ID, FEED_DATE, TXN_DATE, PARTNER,
    MILES_REDEEMED, STATUS, MEMBER_JOIN_STATUS, SOURCE_FILE, INGESTED_AT
) VALUES (
    s.TXN_ID, s.GLOBAL_MEMBER_ID, s.FEED_MEMBER_ID, s.FEED_DATE, s.TXN_DATE,
    s.PARTNER, s.MILES_REDEEMED, s.STATUS, s.MEMBER_JOIN_STATUS,
    s.SOURCE_FILE, s.INGESTED_AT
);

-- 6) Operational DQ checks (alert/stop policy is configured by severity).
-- Duplicate transaction IDs:
SELECT TXN_ID, COUNT(*) AS ROW_COUNT
FROM SKYPOINTS_CURATED.REDEMPTION_FLAT
GROUP BY TXN_ID HAVING COUNT(*) > 1;

-- More than one canonical current row for a golden member:
SELECT GLOBAL_MEMBER_ID, COUNT(*) AS ROW_COUNT
FROM SKYPOINTS_CURATED.MEMBER_CURRENT
GROUP BY GLOBAL_MEMBER_ID HAVING COUNT(*) > 1;

-- More than one current country row for a golden member:
SELECT GLOBAL_MEMBER_ID, COUNT(*) AS ROW_COUNT
FROM (
  SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_CURATED.TABLE_AUSTRALIA
  UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_CURATED.TABLE_INDIA
  UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS_CURATED.TABLE_USA
)
GROUP BY GLOBAL_MEMBER_ID HAVING COUNT(*) > 1;

-- Required data and basic domain checks:
SELECT * FROM SKYPOINTS_CURATED.MEMBER_CURRENT
WHERE GLOBAL_MEMBER_ID IS NULL OR MEMBER_NAME IS NULL OR ENROLLMENT_DATE IS NULL
   OR (TIER_CODE IS NOT NULL AND LENGTH(TIER_CODE) > 5)
   OR (IS_ACTIVE IS NOT NULL AND IS_ACTIVE NOT IN ('A','I','Y','N'));


-- Additional source-contract and reconciliation diagnostics.
-- Duplicate current source-to-golden mappings must be resolved before promotion.
SELECT SOURCE_COUNTRY, SOURCE_MEMBER_ID, COUNT(*) AS CURRENT_MAPPING_COUNT
FROM SKYPOINTS_RAW.MEMBER_IDENTITY_MAP
WHERE IS_CURRENT = TRUE
GROUP BY SOURCE_COUNTRY, SOURCE_MEMBER_ID
HAVING COUNT(*) > 1;

-- A repeated member display name is diagnostic, not a failed member key check.
SELECT MEMBER_NAME, COUNT(DISTINCT GLOBAL_MEMBER_ID) AS GLOBAL_MEMBER_COUNT
FROM SKYPOINTS_CURATED.MEMBER_CURRENT
GROUP BY MEMBER_NAME
HAVING COUNT(DISTINCT GLOBAL_MEMBER_ID) > 1;

-- Source-local member keys must be unique within the delivered country batch.
SELECT BATCH_ID, SOURCE_COUNTRY,
       RAW_PAYLOAD:source_member_id::STRING AS SOURCE_MEMBER_ID,
       COUNT(*) AS ROW_COUNT
FROM SKYPOINTS_RAW.RAW_MEMBER_LANDING
GROUP BY BATCH_ID, SOURCE_COUNTRY, RAW_PAYLOAD:source_member_id::STRING
HAVING COUNT(*) > 1;

-- Date/domain checks that should produce warnings or rejects per data contract.
SELECT * FROM SKYPOINTS_CURATED.MEMBER_CURRENT
WHERE DOB > CURRENT_DATE()
   OR ENROLLMENT_DATE > CURRENT_DATE()
   OR LAST_FLIGHT_DATE > CURRENT_DATE()
   OR (POSTAL_CODE IS NOT NULL AND LENGTH(TO_VARCHAR(POSTAL_CODE)) > 5);

-- Batch reconciliation: landed rows must equal accepted + rejected rows;
-- superseded profile versions are accepted history, not rejects.
SELECT BATCH_ID, LANDED_ROW_COUNT, ACCEPTED_ROW_COUNT, REJECTED_ROW_COUNT,
       LANDED_ROW_COUNT - ACCEPTED_ROW_COUNT - REJECTED_ROW_COUNT AS UNACCOUNTED_ROWS
FROM SKYPOINTS_RAW.PIPELINE_BATCH_AUDIT
WHERE STATUS = 'PUBLISHED'
  AND LANDED_ROW_COUNT <> ACCEPTED_ROW_COUNT + REJECTED_ROW_COUNT;
