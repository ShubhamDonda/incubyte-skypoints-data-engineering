USING BATCH_MEMBER_WINNERS s
ON t.GLOBAL_MEMBER_ID = s.GLOBAL_MEMBER_ID
WHEN MATCHED
 AND (s.SOURCE_UPDATED_AT > t.SOURCE_UPDATED_AT
      OR (s.SOURCE_UPDATED_AT = t.SOURCE_UPDATED_AT AND s.INGESTED_AT > t.INGESTED_AT)) THEN UPDATE SET
    SOURCE_COUNTRY = s.SOURCE_COUNTRY,
    SOURCE_MEMBER_ID = s.SOURCE_MEMBER_ID,
    MEMBER_NAME = s.MEMBER_NAME,
    DOB = s.DOB,
    ENROLLMENT_DATE = s.ENROLLMENT_DATE,
    LAST_FLIGHT_DATE = s.LAST_FLIGHT_DATE,
