-- Assumptions: a country-aware ingestion adapter has parsed each CSV row into
-- RAW_MEMBER_LANDING.RAW_PAYLOAD with canonical keys and source-specific dates
-- normalized to ISO-8601. It preserves the original payload in the raw layer.
-- The adapter resolves SOURCE_MEMBER_ID to GLOBAL_MEMBER_ID via MEMBER_IDENTITY_MAP.

-- The following statements are replay-safe for a batch: remove any prior staging
-- and reject rows for this batch before repopulating them.
DELETE FROM SKYPOINTS_CURATED.STG_MEMBER WHERE BATCH_ID = :BATCH_ID;
DELETE FROM SKYPOINTS_RAW.DQ_REJECTS WHERE BATCH_ID = :BATCH_ID;

-- 1) Build typed staging rows. TRY_TO_DATE prevents malformed values from
-- crashing a batch; mandatory parse failures are inserted into DQ_REJECTS.
INSERT INTO SKYPOINTS_CURATED.STG_MEMBER (
    GLOBAL_MEMBER_ID, SOURCE_COUNTRY, SOURCE_MEMBER_ID, MEMBER_NAME, DOB,
    ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE_CODE,
    POSTAL_CODE, IS_ACTIVE, MEMBER_TYPE, SOURCE_UPDATED_AT, INGESTED_AT,
    SOURCE_FILE, SOURCE_ROW_NUMBER, AGE, STALE_MEMBER, RECORD_HASH, BATCH_ID
)
SELECT
    im.GLOBAL_MEMBER_ID,
    r.SOURCE_COUNTRY,
    p.SOURCE_MEMBER_ID,
    p.MEMBER_NAME,
    TRY_TO_DATE(NULLIF(p.DOB, '')),
    TRY_TO_DATE(NULLIF(p.ENROLLMENT_DATE, '')),
    TRY_TO_DATE(NULLIF(p.LAST_FLIGHT_DATE, '')),
    NULLIF(p.TIER_CODE, ''), NULLIF(p.AGENT_NAME, ''),
    NULLIF(p.STATE_CODE, ''), TRY_TO_NUMBER(NULLIF(p.POSTAL_CODE, '')),
    NULLIF(p.IS_ACTIVE, ''), NULLIF(p.MEMBER_TYPE, ''),
    COALESCE(p.SOURCE_UPDATED_AT::TIMESTAMP_TZ, r.INGESTED_AT),
    r.INGESTED_AT, r.SOURCE_FILE, r.SOURCE_ROW_NUMBER,
    IFF(p.DOB IS NULL OR TRY_TO_DATE(p.DOB) IS NULL, NULL,
        DATEDIFF(YEAR, TRY_TO_DATE(p.DOB), CURRENT_DATE())
        - IFF(TO_CHAR(CURRENT_DATE(), 'MMDD') < TO_CHAR(TRY_TO_DATE(p.DOB), 'MMDD'), 1, 0)),
    COALESCE(DATEDIFF(DAY, TRY_TO_DATE(p.LAST_FLIGHT_DATE), CURRENT_DATE()) > 90, FALSE),
    r.RECORD_HASH, r.BATCH_ID
FROM SKYPOINTS_RAW.RAW_MEMBER_LANDING r
CROSS JOIN LATERAL (
    SELECT
        r.RAW_PAYLOAD:source_member_id::STRING AS SOURCE_MEMBER_ID,
        r.RAW_PAYLOAD:member_name::STRING AS MEMBER_NAME,
        r.RAW_PAYLOAD:dob::STRING AS DOB,
        r.RAW_PAYLOAD:enrollment_date::STRING AS ENROLLMENT_DATE,
        r.RAW_PAYLOAD:last_flight_date::STRING AS LAST_FLIGHT_DATE,
        r.RAW_PAYLOAD:tier_code::STRING AS TIER_CODE,
        r.RAW_PAYLOAD:agent_name::STRING AS AGENT_NAME,
        r.RAW_PAYLOAD:state_code::STRING AS STATE_CODE,
        r.RAW_PAYLOAD:postal_code::STRING AS POSTAL_CODE,
        r.RAW_PAYLOAD:is_active::STRING AS IS_ACTIVE,
        r.RAW_PAYLOAD:member_type::STRING AS MEMBER_TYPE,
        r.RAW_PAYLOAD:source_updated_at::STRING AS SOURCE_UPDATED_AT
) p
JOIN SKYPOINTS_RAW.MEMBER_IDENTITY_MAP im
  ON im.SOURCE_COUNTRY = r.SOURCE_COUNTRY
 AND im.SOURCE_MEMBER_ID = p.SOURCE_MEMBER_ID
 AND im.IS_CURRENT = TRUE
WHERE r.BATCH_ID = :BATCH_ID
  AND NULLIF(p.SOURCE_MEMBER_ID, '') IS NOT NULL
  AND NULLIF(p.MEMBER_NAME, '') IS NOT NULL
  AND TRY_TO_DATE(NULLIF(p.ENROLLMENT_DATE, '')) IS NOT NULL;

-- 2) Reject records failing mandatory checks. The production adapter should
-- also validate field lengths, date contracts, duplicate source keys, enums,
-- and malformed optional fields before or during this promotion.
INSERT INTO SKYPOINTS_RAW.DQ_REJECTS (BATCH_ID, SOURCE_FILE, SOURCE_ROW_NUMBER, RAW_PAYLOAD, ERROR_CODES)
SELECT r.BATCH_ID, r.SOURCE_FILE, r.SOURCE_ROW_NUMBER, r.RAW_PAYLOAD,
       ARRAY_CONSTRUCT_COMPACT(
         IFF(NULLIF(r.RAW_PAYLOAD:source_member_id::STRING, '') IS NULL, 'MISSING_MEMBER_ID', NULL),
         IFF(NULLIF(r.RAW_PAYLOAD:member_name::STRING, '') IS NULL, 'MISSING_MEMBER_NAME', NULL),
         IFF(TRY_TO_DATE(NULLIF(r.RAW_PAYLOAD:enrollment_date::STRING, '')) IS NULL, 'INVALID_OR_MISSING_ENROLLMENT_DATE', NULL),
         IFF(im.GLOBAL_MEMBER_ID IS NULL, 'MISSING_GLOBAL_ID_MAPPING', NULL)
       )
FROM SKYPOINTS_RAW.RAW_MEMBER_LANDING r
LEFT JOIN SKYPOINTS_RAW.MEMBER_IDENTITY_MAP im
  ON im.SOURCE_COUNTRY = r.SOURCE_COUNTRY
 AND im.SOURCE_MEMBER_ID = r.RAW_PAYLOAD:source_member_id::STRING
 AND im.IS_CURRENT = TRUE
WHERE r.BATCH_ID = :BATCH_ID
  AND (NULLIF(r.RAW_PAYLOAD:source_member_id::STRING, '') IS NULL
    OR NULLIF(r.RAW_PAYLOAD:member_name::STRING, '') IS NULL
    OR TRY_TO_DATE(NULLIF(r.RAW_PAYLOAD:enrollment_date::STRING, '')) IS NULL
    OR im.GLOBAL_MEMBER_ID IS NULL);

-- 3) Latest source state wins for each immutable golden member ID. Never use
-- MEMBER_NAME as the key. SOURCE_UPDATED_AT is preferred; INGESTED_AT is only
-- a fallback until the source provides a trustworthy change timestamp.
-- If this preflight returns rows, stop the batch: there is no evidence to pick
-- a winner among different payloads with identical timestamps.
-- Also compare against the previously published current row. If this returns
-- rows, stop the batch rather than allowing a timestamp tie to hide a conflict.
SELECT s.GLOBAL_MEMBER_ID
FROM SKYPOINTS_CURATED.STG_MEMBER s
JOIN SKYPOINTS_CURATED.MEMBER_CURRENT t
  ON t.GLOBAL_MEMBER_ID = s.GLOBAL_MEMBER_ID
WHERE s.BATCH_ID = :BATCH_ID
  AND s.SOURCE_UPDATED_AT = t.SOURCE_UPDATED_AT
  AND s.INGESTED_AT = t.INGESTED_AT
  AND s.RECORD_HASH <> t.RECORD_HASH;
SELECT GLOBAL_MEMBER_ID, SOURCE_UPDATED_AT, INGESTED_AT,
       COUNT(DISTINCT RECORD_HASH) AS CONFLICTING_VERSIONS
FROM SKYPOINTS_CURATED.STG_MEMBER
WHERE BATCH_ID = :BATCH_ID
GROUP BY GLOBAL_MEMBER_ID, SOURCE_UPDATED_AT, INGESTED_AT
HAVING COUNT(DISTINCT RECORD_HASH) > 1;

-- Materialize only this batch's winner set. The country delivery merges below
-- use this narrow set instead of rescanning every member in MEMBER_CURRENT.
CREATE OR REPLACE TEMPORARY TABLE BATCH_MEMBER_WINNERS AS
SELECT *
FROM SKYPOINTS_CURATED.STG_MEMBER
WHERE BATCH_ID = :BATCH_ID
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY GLOBAL_MEMBER_ID
    ORDER BY SOURCE_UPDATED_AT DESC, INGESTED_AT DESC,
             SOURCE_COUNTRY DESC, SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
) = 1;

