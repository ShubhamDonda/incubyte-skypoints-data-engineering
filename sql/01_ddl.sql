-- SkyPoints reference DDL for Snowflake.
-- Country-specific tables are delivery tables; MEMBER_CURRENT is the canonical
-- current-state table that enforces one current country per global member.

CREATE SCHEMA IF NOT EXISTS SKYPOINTS_RAW;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_CURATED;

CREATE OR REPLACE TABLE SKYPOINTS_RAW.RAW_MEMBER_LANDING (
    SOURCE_COUNTRY       VARCHAR(3)   NOT NULL,
    SOURCE_FILE          VARCHAR(500) NOT NULL,
    SOURCE_ROW_NUMBER    NUMBER(38,0),
    RAW_PAYLOAD          VARIANT      NOT NULL,
    INGESTED_AT          TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID             VARCHAR(100) NOT NULL,
    RECORD_HASH          VARCHAR(64)
);

CREATE OR REPLACE TABLE SKYPOINTS_RAW.RAW_REDEMPTION_LANDING (
    SOURCE_FILE          VARCHAR(500) NOT NULL,
    RAW_PAYLOAD          VARIANT      NOT NULL,
    INGESTED_AT          TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID             VARCHAR(100) NOT NULL,
    RECORD_HASH          VARCHAR(64)
);

-- A country-scoped source key is needed because the supplied sample files
-- repeat IDs 1, 2, 3. Multiple source keys may map to one immutable golden ID
-- when an airline member moves between country source systems.
CREATE OR REPLACE TABLE SKYPOINTS_RAW.MEMBER_IDENTITY_MAP (
    SOURCE_COUNTRY       VARCHAR(3)   NOT NULL,
    SOURCE_MEMBER_ID     VARCHAR(18)  NOT NULL,
    GLOBAL_MEMBER_ID     VARCHAR(64)  NOT NULL,
    VALID_FROM           TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    VALID_TO             TIMESTAMP_TZ,
    IS_CURRENT           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT UQ_MEMBER_IDENTITY UNIQUE (SOURCE_COUNTRY, SOURCE_MEMBER_ID, IS_CURRENT)
);

CREATE OR REPLACE TABLE SKYPOINTS_CURATED.STG_MEMBER (
    GLOBAL_MEMBER_ID     VARCHAR(64)  NOT NULL,
    SOURCE_COUNTRY       VARCHAR(3)   NOT NULL,
    SOURCE_MEMBER_ID     VARCHAR(18)  NOT NULL,
    MEMBER_NAME          VARCHAR(255) NOT NULL,
    DOB                  DATE,
    ENROLLMENT_DATE      DATE         NOT NULL,
    LAST_FLIGHT_DATE     DATE,
    TIER_CODE            VARCHAR(5),
    AGENT_NAME           VARCHAR(255),
    STATE_CODE           VARCHAR(5),
    POSTAL_CODE          NUMBER(5,0),
    IS_ACTIVE            VARCHAR(1),
    MEMBER_TYPE          VARCHAR(1),
    SOURCE_UPDATED_AT    TIMESTAMP_TZ,
    INGESTED_AT          TIMESTAMP_TZ NOT NULL,
    SOURCE_FILE          VARCHAR(500) NOT NULL,
    SOURCE_ROW_NUMBER    NUMBER(38,0),
    AGE                  NUMBER(3,0),
    STALE_MEMBER         BOOLEAN,
    RECORD_HASH          VARCHAR(64),
    BATCH_ID             VARCHAR(100) NOT NULL
);

CREATE OR REPLACE TABLE SKYPOINTS_CURATED.MEMBER_CURRENT (
    GLOBAL_MEMBER_ID     VARCHAR(64)  NOT NULL,
    SOURCE_COUNTRY       VARCHAR(3)   NOT NULL,
    SOURCE_MEMBER_ID     VARCHAR(18)  NOT NULL,
    MEMBER_NAME          VARCHAR(255) NOT NULL,
    DOB                  DATE,
    ENROLLMENT_DATE      DATE         NOT NULL,
    LAST_FLIGHT_DATE     DATE,
    TIER_CODE            VARCHAR(5),
    AGENT_NAME           VARCHAR(255),
    STATE_CODE           VARCHAR(5),
    POSTAL_CODE          NUMBER(5,0),
    IS_ACTIVE            VARCHAR(1),
    MEMBER_TYPE          VARCHAR(1),
    AGE                  NUMBER(3,0),
    STALE_MEMBER         BOOLEAN      NOT NULL,
    SOURCE_UPDATED_AT    TIMESTAMP_TZ,
    INGESTED_AT          TIMESTAMP_TZ NOT NULL,
    SOURCE_FILE          VARCHAR(500) NOT NULL,
    RECORD_HASH          VARCHAR(64),
    LAST_BATCH_ID        VARCHAR(100) NOT NULL,
    UPDATED_AT           TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY (SOURCE_COUNTRY, TO_DATE(INGESTED_AT));

-- Country-specific targets. Keep the same shape so downstream consumers
-- have a stable contract. Add countries by controlled DDL/deployment, not raw input.
CREATE OR REPLACE TABLE SKYPOINTS_CURATED.TABLE_AUSTRALIA LIKE SKYPOINTS_CURATED.MEMBER_CURRENT;
CREATE OR REPLACE TABLE SKYPOINTS_CURATED.TABLE_INDIA     LIKE SKYPOINTS_CURATED.MEMBER_CURRENT;
CREATE OR REPLACE TABLE SKYPOINTS_CURATED.TABLE_USA       LIKE SKYPOINTS_CURATED.MEMBER_CURRENT;

CREATE OR REPLACE TABLE SKYPOINTS_CURATED.REDEMPTION_FLAT (
    TXN_ID               VARCHAR(64)  NOT NULL,
    GLOBAL_MEMBER_ID     VARCHAR(64),
    FEED_MEMBER_ID       VARCHAR(64)  NOT NULL,
    FEED_DATE            DATE         NOT NULL,
    TXN_DATE             DATE         NOT NULL,
    PARTNER              VARCHAR(255),
    MILES_REDEEMED       NUMBER(18,0) NOT NULL,
    STATUS               VARCHAR(30),
    MEMBER_JOIN_STATUS   VARCHAR(30)  NOT NULL,
    SOURCE_FILE          VARCHAR(500) NOT NULL,
    INGESTED_AT          TIMESTAMP_TZ NOT NULL
);

CREATE OR REPLACE TABLE SKYPOINTS_RAW.DQ_REJECTS (
    BATCH_ID             VARCHAR(100) NOT NULL,
    SOURCE_FILE          VARCHAR(500) NOT NULL,
    SOURCE_ROW_NUMBER    NUMBER(38,0),
    RAW_PAYLOAD          VARIANT,
    ERROR_CODES          ARRAY NOT NULL,
    REJECTED_AT          TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- Snowflake does not enforce ordinary PRIMARY KEY / UNIQUE constraints on
-- standard tables. Enforce uniqueness in the pipeline and monitor DQ queries.


CREATE OR REPLACE TABLE SKYPOINTS_RAW.PIPELINE_BATCH_AUDIT (
    BATCH_ID             VARCHAR(100) NOT NULL,
    FEED_TYPE            VARCHAR(30)  NOT NULL,
    SOURCE_COUNTRY       VARCHAR(3),
    STATUS               VARCHAR(20)  NOT NULL,
    EXPECTED_ROW_COUNT   NUMBER(38,0),
    LANDED_ROW_COUNT     NUMBER(38,0),
    ACCEPTED_ROW_COUNT   NUMBER(38,0),
    REJECTED_ROW_COUNT   NUMBER(38,0),
    STARTED_AT           TIMESTAMP_TZ NOT NULL,
    COMPLETED_AT         TIMESTAMP_TZ,
    ERROR_MESSAGE        VARCHAR(4000),
    CODE_VERSION         VARCHAR(100)
);
